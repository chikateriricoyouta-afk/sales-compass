import type { AbilityKey } from "../types";

// 「次の商談でやること3つ」(Ver.1)。抽象的な助言ではなく、
// 「商談前に何を考えるか・実際に何と言うか」まで具体化して提示する。
//
// 構成:
//   ① 相手を深掘りする質問  : 最もスコアが低い能力(ability #1)に関する一手
//   ② 次の具体的行動を決める: 2番目にスコアが低い能力(ability #2)に関する締めの一手
//   ③ 商談後30秒で振り返る : 誰にでも使える固定の振り返り習慣
//
// 【設計思想】『頭のいい人が話す前に考えていること』(安達裕哉)を基準にしている。
//   - 第5法則「伝わらないのは、話し方ではなく考えが足りないせい」
//     → 一言(script)だけ渡しても再現性がない。必ず think(話す前に考えること)とセットで出す。
//   - 第3法則「人はちゃんと考えてくれてる人を信頼する」
//     → 信頼は気の利いた一言ではなく、事前に考えてきた形跡から生まれる。
//
// スクリプトに使う型(教科書的な一般論は使わない):
//   1. 断る許可を先に渡す      → 相手の緊張が解けて本音が出る
//   2. 二択で聞く              → オープンな質問より答えやすく、違えば相手が自分で訂正してくれる
//   3. 相手の言葉をそのまま引用 → 「聞いてくれている」が伝わり、相手が自分から話を広げる
//   4. 「なぜ」を「いつ・誰が」に置き換える → 詰問にならず、原因と緊急度が同時に出る

export interface NextAction {
  step: number;
  heading: string;
  /** 話す前に考えること。これがないと script は単なる物真似になる */
  think: string;
  action: string;
  scripts: string[];
}

interface AbilityScript {
  think: string;
  action: string;
  scripts: string[];
}

